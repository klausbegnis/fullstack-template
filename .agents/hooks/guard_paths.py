#!/usr/bin/env python3
"""PreToolUse guard: refuse the edits and commands no review can undo.

Three prose rules become hard stops here — never hand-edit orval output, never
edit a migration that is already on `origin/main`, never touch the block
`next dev` regenerates inside `frontend/AGENTS.md` — plus three shell commands
that bypass a gate rather than pass it.

Reads the harness event on stdin. Denies with the Codex JSON response when Codex
sent the event, and with exit 2 plus a stderr reason for Claude Code.
"""

from __future__ import annotations

import json
import os
import re
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from hook_io import harness_of, paths_of, read_event, repo_root

GENERATED_DIR = "frontend/src/lib/api/generated/"
MIGRATIONS_DIR = "backend/alembic/versions/"
MANAGED_FILE = "frontend/AGENTS.md"
MANAGED_BEGIN = "<!-- BEGIN:nextjs-agent-rules -->"
MANAGED_END = "<!-- END:nextjs-agent-rules -->"

GIT_COMMIT_NO_VERIFY = re.compile(r"\bgit\s+commit\b[^\n]*?(?:--no-verify|(?<!\S)-n(?!\S))")
GIT_FORCE_PUSH = re.compile(r"\bgit\s+push\b[^\n]*?(?:--force(?:-with-lease)?\b|(?<!\S)-f(?!\S))")
MAIN_REF = re.compile(r"(?:^|\s|:)main(?:\s|$)")
ALEMBIC_REVISION = re.compile(r"\balembic\s+revision\b")
CREATE_MIGRATION = "app.commands.create_migration"


def deny(harness: str, reason: str) -> int:
    if harness == "codex":
        print(
            json.dumps(
                {
                    "hookSpecificOutput": {
                        "hookEventName": "PreToolUse",
                        "permissionDecision": "deny",
                        "permissionDecisionReason": reason,
                    }
                }
            )
        )
        return 0
    print(reason, file=sys.stderr)
    return 2


def tracked_on_main(root: str, path: str) -> bool:
    for ref in ("origin/main", "main"):
        try:
            result = subprocess.run(
                ["git", "cat-file", "-e", f"{ref}:{path}"],
                cwd=root,
                capture_output=True,
                check=False,
            )
        except OSError:
            return False
        if result.returncode == 0:
            return True
    return False


def managed_block(root: str) -> str:
    target = os.path.join(root, MANAGED_FILE)
    try:
        with open(target, encoding="utf-8") as handle:
            text = handle.read()
    except OSError:
        return ""
    start = text.find(MANAGED_BEGIN)
    end = text.find(MANAGED_END)
    if start == -1 or end == -1 or end < start:
        return ""
    return text[start : end + len(MANAGED_END)]


def touches_managed_block(event: dict, root: str) -> bool:
    block = managed_block(root)
    if not block:
        return False
    tool_input = event.get("tool_input") or {}
    if event.get("tool_name") == "Write":
        return True
    candidates = [
        tool_input.get(key)
        for key in ("old_string", "new_string", "command", "patch", "content")
    ]
    for candidate in candidates:
        if not isinstance(candidate, str):
            continue
        if MANAGED_BEGIN in candidate or MANAGED_END in candidate:
            return True
        for line in candidate.splitlines():
            stripped = line.lstrip("+- ").strip()
            if len(stripped) > 12 and stripped in block:
                return True
    return False


def check_paths(event: dict, root: str) -> str | None:
    for path in paths_of(event):
        posix = path.replace(os.sep, "/")
        if posix.startswith(GENERATED_DIR):
            return (
                f"{posix} is orval output. It is regenerated by `npm run generate:api` "
                f"and never hand-edited or committed. Change `backend/openapi.json` "
                f"(via `uv run python -m app.commands.export_openapi`) and regenerate."
            )
        if posix.startswith(MIGRATIONS_DIR) and posix.endswith(".py"):
            if tracked_on_main(root, posix):
                return (
                    f"{posix} already exists on origin/main. A merged migration is "
                    f"immutable — add a new revision with "
                    f"`uv run python -m app.commands.create_migration -m \"<msg>\"` instead."
                )
        if posix == MANAGED_FILE and touches_managed_block(event, root):
            return (
                f"{MANAGED_FILE} carries the block `next dev` regenerates between "
                f"{MANAGED_BEGIN} and {MANAGED_END}. Edits there are overwritten on the "
                f"next dev-server start; the canonical rules live in the root AGENTS.md."
            )
    return None


def check_bash(event: dict) -> str | None:
    tool_input = event.get("tool_input") or {}
    command = tool_input.get("command")
    if not isinstance(command, str) or not command.strip():
        return None
    if GIT_COMMIT_NO_VERIFY.search(command):
        return (
            "`git commit --no-verify` skips .githooks/pre-commit, which is the "
            "change-scoped smoke gate. If the hook fails, the work is not done — fix it."
        )
    if GIT_FORCE_PUSH.search(command) and MAIN_REF.search(command):
        return (
            "Force-pushing main rewrites shared history. Push a branch and open a "
            "pull request instead."
        )
    if ALEMBIC_REVISION.search(command) and CREATE_MIGRATION not in command:
        return (
            "`alembic revision` leaves the auto-generated banner comments that the "
            "no-comments contract rejects. Run "
            "`uv run python -m app.commands.create_migration -m \"<msg>\"` instead."
        )
    return None


def main() -> int:
    event = read_event()
    if not event:
        return 0
    harness = harness_of(event)
    root = repo_root(event.get("cwd"))

    reason = check_bash(event) if event.get("tool_name") == "Bash" else check_paths(event, root)
    if reason:
        return deny(harness, reason)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
